import Foundation
import Observation

/// State and logic for the Dashboard tab.
/// Reads live data from the shared on-device automation engine.
@Observable
final class DashboardViewModel {

    private let engine: PpsrAutomationEngine

    init(engine: PpsrAutomationEngine) {
        self.engine = engine
    }

    // MARK: - Computed (delegated to engine)

    var stats: PpsrStats { engine.stats }
    var status: PpsrStatus { engine.status }
    var progress: PpsrProgress { engine.progress }
    var results: [PpsrResult] { engine.results }
    var errorMessage: String? { engine.errorMessage }

    var isRunning: Bool { engine.isRunning }

    /// Number of cards currently queued/waiting to be tested.
    var queuedCardCount: Int { engine.cards.count }
    var hasQueuedCards: Bool { !engine.cards.isEmpty }

    /// The auto-generated email for the current run (nil if auto-generate is off or no run yet).
    var currentRunEmail: String? { engine.currentRunEmail }

    /// Whether auto-generate is enabled on the engine.
    var autoGenerateData: Bool { engine.autoGenerateData }

    /// Success-rate trend (last 10 results) as percentages 0–100.
    var successRateTrend: [Double] {
        let recent = results.suffix(10)
        guard !recent.isEmpty else { return [] }
        var trend: [Double] = []
        var success = 0
        for (index, result) in recent.enumerated() {
            if ResultStatus.from(result.status) == .resultsFound {
                success += 1
            }
            let rate = Double(success) / Double(index + 1) * 100.0
            trend.append(rate)
        }
        return trend
    }

    /// Doughnut chart segments keyed by status category.
    var chartSegments: [(status: ResultStatus, count: Int)] {
        [
            (.resultsFound, stats.successCount),
            (.paymentError, stats.failureCount),
            (.unknown, stats.unknownCount),
            (.noResults, stats.noResultsCount),
        ].filter { $0.count > 0 }
    }

    // MARK: - Actions

    /// Start the automation.
    func start(email: String) {
        engine.start(email: email)
    }

    /// Stop the automation.
    func stop() {
        engine.stop()
    }

    /// Clear any error message.
    func clearError() {
        engine.clearError()
    }
}
