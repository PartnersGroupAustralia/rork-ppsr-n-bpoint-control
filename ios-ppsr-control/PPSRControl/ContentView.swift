import SwiftUI

/// Root view — shows onboarding on first launch, then the main TabView.
/// Creates the shared on-device automation engine passed to all tabs.
struct ContentView: View {
    @State private var settings = AppSettings()
    @State private var engine = PpsrAutomationEngine()

    var body: some View {
        Group {
            if settings.hasCompletedOnboarding {
                MainTabView(settings: settings, engine: engine)
            } else {
                OnboardingView(settings: settings)
            }
        }
        .tint(.accentColor)
        .onChange(of: settings.autoGenerateData) { _, newValue in
            engine.autoGenerateData = newValue
        }
        .onChange(of: settings.autoRetryEnabled) { _, newValue in
            engine.autoRetryEnabled = newValue
        }
        .onChange(of: settings.backgroundProcessingEnabled) { _, newValue in
            engine.backgroundProcessingEnabled = newValue
        }
        .onChange(of: settings.automationMode) { _, newValue in
            engine.mode = newValue
        }
        .onChange(of: settings.bpointAmount) { _, newValue in
            engine.bpointAmount = newValue
        }
        .onAppear {
            engine.autoGenerateData = settings.autoGenerateData
            engine.autoRetryEnabled = settings.autoRetryEnabled
            engine.backgroundProcessingEnabled = settings.backgroundProcessingEnabled
            engine.mode = settings.automationMode
            engine.bpointAmount = settings.bpointAmount
        }
    }
}

/// Main tabbed interface with Dashboard, Results, Successful, Cards, Settings.
struct MainTabView: View {
    let settings: AppSettings
    let engine: PpsrAutomationEngine

    var body: some View {
        TabView {
            DashboardView(settings: settings, engine: engine)
                .tabItem {
                    Label("Dashboard", systemImage: "gauge.with.dots.and.needle.bottom.50percent")
                }

            LiveView(engine: engine)
                .tabItem {
                    Label("Live", systemImage: "eye.fill")
                }

            ResultsView(engine: engine)
                .tabItem {
                    Label("Results", systemImage: "list.bullet.clipboard")
                }

            SuccessfulView(engine: engine)
                .tabItem {
                    Label("Successful", systemImage: "checkmark.seal")
                }

            CardsView(engine: engine)
                .tabItem {
                    Label("Cards", systemImage: "creditcard")
                }

            SettingsView(settings: settings, engine: engine)
                .tabItem {
                    Label("Settings", systemImage: "gearshape")
                }
        }
    }
}

