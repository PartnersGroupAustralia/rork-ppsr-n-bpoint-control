import Foundation
import SwiftUI

/// Centralized, observable app settings backed by UserDefaults.
/// Holds the PPSR account email and dashboard auto-refresh preference.
@Observable
final class AppSettings {

    /// Email used for PPSR check receipts (persisted).
    var email: String {
        didSet {
            UserDefaults.standard.set(email, forKey: Keys.email)
        }
    }

    /// Whether the user has completed first-launch onboarding (persisted).
    var hasCompletedOnboarding: Bool {
        didSet {
            UserDefaults.standard.set(hasCompletedOnboarding, forKey: Keys.onboarding)
        }
    }

    /// Whether the Dashboard should auto-refresh every 30 seconds while foregrounded (persisted).
    var autoRefreshDashboard: Bool {
        didSet {
            UserDefaults.standard.set(autoRefreshDashboard, forKey: Keys.autoRefresh)
        }
    }

    /// Whether to auto-generate a random VIN and email per run (persisted).
    var autoGenerateData: Bool {
        didSet {
            UserDefaults.standard.set(autoGenerateData, forKey: Keys.autoGenerate)
        }
    }

    /// Whether failed cards are automatically retried (persisted).
    var autoRetryEnabled: Bool {
        didSet {
            UserDefaults.standard.set(autoRetryEnabled, forKey: Keys.autoRetry)
        }
    }

    /// Whether automation continues when the app moves to background (persisted).
    var backgroundProcessingEnabled: Bool {
        didSet {
            UserDefaults.standard.set(backgroundProcessingEnabled, forKey: Keys.backgroundProcessing)
        }
    }

    /// Which flow the Dashboard Start button runs: PPSR checks or Bpoint payments (persisted).
    var automationMode: AutomationMode {
        didSet {
            UserDefaults.standard.set(automationMode.rawValue, forKey: Keys.automationMode)
        }
    }

    /// Amount (AUD) filled into the Bpoint payment form (persisted).
    var bpointAmount: Int {
        didSet {
            UserDefaults.standard.set(bpointAmount, forKey: Keys.bpointAmount)
        }
    }

    /// Selectable Bpoint payment amounts.
    static let bpointAmounts = [10, 50, 150, 300, 500]

    /// Auto-refresh interval in seconds.
    static let autoRefreshInterval: TimeInterval = 30

    init() {
        self.email = UserDefaults.standard.string(forKey: Keys.email) ?? ""
        self.hasCompletedOnboarding = UserDefaults.standard.bool(forKey: Keys.onboarding)
        self.autoRefreshDashboard = UserDefaults.standard.object(forKey: Keys.autoRefresh) as? Bool ?? true
        self.autoGenerateData = UserDefaults.standard.object(forKey: Keys.autoGenerate) as? Bool ?? true
        self.autoRetryEnabled = UserDefaults.standard.object(forKey: Keys.autoRetry) as? Bool ?? true
        self.backgroundProcessingEnabled = UserDefaults.standard.object(forKey: Keys.backgroundProcessing) as? Bool ?? true
        self.automationMode = AutomationMode(rawValue: UserDefaults.standard.string(forKey: Keys.automationMode) ?? "") ?? .ppsr
        self.bpointAmount = UserDefaults.standard.object(forKey: Keys.bpointAmount) as? Int ?? 50
    }

    /// Resets settings to defaults (used in previews/testing).
    func reset() {
        email = ""
        hasCompletedOnboarding = false
        autoRefreshDashboard = true
        autoGenerateData = true
        autoRetryEnabled = true
        backgroundProcessingEnabled = true
        automationMode = .ppsr
        bpointAmount = 50
    }

    private enum Keys {
        static let email = "ppsr.email"
        static let onboarding = "ppsr.hasCompletedOnboarding"
        static let autoRefresh = "ppsr.autoRefreshDashboard"
        static let autoGenerate = "ppsr.autoGenerateData"
        static let autoRetry = "ppsr.autoRetryEnabled"
        static let backgroundProcessing = "ppsr.backgroundProcessingEnabled"
        static let automationMode = "ppsr.automationMode"
        static let bpointAmount = "ppsr.bpointAmount"
    }
}
