    private func screenshotName(for card: CardEntry) -> String {
        let epoch = Int(Date().timeIntervalSince1970)
        let suffix = UUID().uuidString.prefix(8)
        return "ppsr_result_\(epoch)_\(suffix)"
    }

    // MARK: - Status Detection

    /// Determines the PPSR result status from page text content.
    private func determineStatus(from text: String) -> String {
        let lower = text.lowercased()

        // Payment errors
        if lower.contains("payment error") || lower.contains("declined") ||
            lower.contains("payment failed") || lower.contains("card was declined") ||
            lower.contains("transaction failed") || lower.contains("insufficient funds") ||
            lower.contains("error in payment processing") ||
            lower.contains("payment processing") || lower.contains("may have been charged") ||
            lower.contains("financial institution") {
            return "PAYMENT_ERROR"
        }

        // Positive clear result: no security interests registered (URL ends in /CarCheck/result/*)
        if lower.contains("free from debt") || lower.contains("no security interests") ||
            lower.contains("no security interests registered") || lower.contains("clear ppsr search") ||
            lower.contains("there are no security interests") ||
            lower.contains("search certificate") {
            return "RESULTS_FOUND"
        }

        // Results found / encumbrance detected
        if lower.contains("results found") || lower.contains("security interest") ||
            lower.contains("registration") || lower.contains("encumbrance") ||
            lower.contains("1 result") || lower.contains("results (") ||
            lower.contains("vehicle results") {
            return "RESULTS_FOUND"
        }

        // No results / NEVDIS miss — only when the above clear-result phrases aren't present
        if lower.contains("no results") || lower.contains("no match") ||
            lower.contains("no encumbrance") || lower.contains("no encumbrances") ||
            lower.contains("0 results") || lower.contains("vehicle details not found") ||
            lower.contains("vehicle searched") {
            return "NO_RESULTS"
        }

        return "UNKNOWN"
    }

