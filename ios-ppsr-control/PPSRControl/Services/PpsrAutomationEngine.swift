    /// JS to fill payment card details, expiry, CVV, and email on the payment page.
    /// Uses the native-value-setter trick so React/Vue controlled inputs accept the value.
    /// Handles two separate month/year text boxes, select dropdowns, and falls back to
    /// identifying fields by maxlength and DOM position when selectors don't match.
    private func fillPaymentJS(card: String, mm: String, yy: String, cvv: String, email: String) -> String {
        """
        (function() {
            var results = [];
            var filled = new Set();  // track filled elements

            function setNativeValue(el, value) {
                var proto = el.tagName === 'SELECT'
                    ? window.HTMLSelectElement.prototype
                    : window.HTMLInputElement.prototype;
                var nativeSetter = Object.getOwnPropertyDescriptor(proto, 'value');
                if (nativeSetter && nativeSetter.set) {
                    nativeSetter.set.call(el, value);
                } else {
                    el.value = value;
                }
                el.dispatchEvent(new Event('input', {bubbles: true}));
                el.dispatchEvent(new Event('change', {bubbles: true}));
                el.dispatchEvent(new Event('blur', {bubbles: true}));
            }

            function fillField(selectors, value) {
                for (var i = 0; i < selectors.length; i++) {
                    var els = document.querySelectorAll(selectors[i]);
                    for (var j = 0; j < els.length; j++) {
                        var el = els[j];
                        if (filled.has(el)) continue;
                        el.focus();
                        setNativeValue(el, value);
                        filled.add(el);
                        results.push(selectors[i] + '=' + value);
                        return true;
                    }
                }
                return false;
            }

            function fillSelect(selectors, value) {
                for (var i = 0; i < selectors.length; i++) {
                    var el = document.querySelector(selectors[i]);
                    if (el && el.tagName === 'SELECT' && !filled.has(el)) {
                        el.focus();
                        setNativeValue(el, value);
                        filled.add(el);
                        results.push('select:' + selectors[i] + '=' + value);
                        return true;
                    }
                }
                return false;
            }

            // -- Dump all inputs on page for debugging --
            var allInputs = document.querySelectorAll('input, select');
            var dump = [];
            for (var d = 0; d < allInputs.length; d++) {
                var inp = allInputs[d];
                dump.push(inp.tagName + ' name=' + (inp.name||'') + ' id=' + (inp.id||'') +
                    ' type=' + (inp.type||'') + ' ml=' + (inp.maxLength||'') +
                    ' ph=' + (inp.placeholder||'') + ' ac=' + (inp.autocomplete||''));
            }
            results.push('FIELDS[' + dump.join(' | ') + ']');

            // -- Card number --
            var cardFilled = fillField([
                'input[name*="cardNumber"]', 'input[name*="card_number"]',
                'input[name*="ccNumber"]', 'input[name*="cc_number"]',
                'input[name="cc"]', 'input[name="card"]',
                'input[id*="cardNumber"]', 'input[id*="card_number"]',
                'input[id*="ccNumber"]', 'input[id="card"]',
                'input[id*="creditCard"]', 'input[autocomplete="cc-number"]',
                'input[autocomplete*="cc-number"]',
                'input[placeholder*="card number"]', 'input[placeholder*="Card number"]',
                'input[placeholder*="Card Number"]',
                'input[placeholder*="credit card"]', 'input[placeholder*="Credit Card"]'
            ], '\(card)');

            // If card number didn't match by selector, find the longest maxlength text input
            if (!cardFilled) {
                var textInputs = Array.from(document.querySelectorAll('input[type="text"], input:not([type])'))
                    .filter(function(el) { return !filled.has(el) && el.maxLength >= 12; });
                if (textInputs.length > 0) {
                    fillElement(textInputs[0], '\(card)', 'cardFallback');
                }
            }

            // -- Month (separate text box) --
            var monthFilled = fillField([
                'input[name*="expiryMonth"]', 'input[name*="exp_month"]',
                'input[name*="expMonth"]', 'input[name*="ccExpMonth"]',
                'input[id*="expiryMonth"]', 'input[id*="expMonth"]',
                'input[id*="exp_month"]', 'input[id*="month"]',
                'input[id*="Month"]', 'input[autocomplete="cc-exp-month"]',
                'input[autocomplete*="cc-exp-month"]',
                'input[placeholder*="MM"]', 'input[placeholder*="Month"]',
                'input[placeholder*="month"]'
            ], '\(mm)');

            fillSelect([
                'select[name*="month"]', 'select[id*="month"]',
                'select[name*="Month"]', 'select[id*="Month"]',
                'select[name*="expMonth"]', 'select[id*="expMonth"]'
            ], '\(mm)');

            // -- Year (separate text box) --
            var yearFilled = fillField([
                'input[name*="expiryYear"]', 'input[name*="exp_year"]',
                'input[name*="expYear"]', 'input[name*="ccExpYear"]',
                'input[id*="expiryYear"]', 'input[id*="expYear"]',
                'input[id*="exp_year"]', 'input[id*="year"]',
                'input[id*="Year"]', 'input[autocomplete="cc-exp-year"]',
                'input[autocomplete*="cc-exp-year"]',
                'input[placeholder*="YY"]', 'input[placeholder*="Year"]',
                'input[placeholder*="year"]'
            ], '\(yy)');

            fillSelect([
                'select[name*="year"]', 'select[id*="year"]',
                'select[name*="Year"]', 'select[id*="Year"]',
                'select[name*="expYear"]', 'select[id*="expYear"]'
            ], '\(yy)');

            // -- Smart fallback: if month or year not filled, find by maxlength + position --
            // After card number, the next two short text inputs (maxlength 2) are month and year.
            if (!monthFilled || !yearFilled) {
                var shortInputs = Array.from(document.querySelectorAll('input[type="text"], input:not([type]), input[type="tel"], input[type="number"]'))
                    .filter(function(el) {
                        return !filled.has(el) &&
                               (el.maxLength === 2 || el.maxLength === -1) &&
                               el.offsetWidth > 0;  // visible
                    });
                // If we couldn't match by maxlength=2, try any remaining short-width inputs
                if (shortInputs.length < 2) {
                    shortInputs = Array.from(document.querySelectorAll('input[type="text"], input:not([type]), input[type="tel"], input[type="number"]'))
                        .filter(function(el) {
                            return !filled.has(el) && el.offsetWidth > 0 && el.offsetWidth < 80;
                        });
                }
                if (!monthFilled && shortInputs.length >= 1) {
                    fillElement(shortInputs[0], '\(mm)', 'monthFallback');
                    shortInputs.shift();
                }
                if (!yearFilled && shortInputs.length >= 1) {
                    fillElement(shortInputs[0], '\(yy)', 'yearFallback');
                    shortInputs.shift();
                }
            }

            // -- CVV --
            var cvvFilled = fillField([
                'input[name*="cvv"]', 'input[name*="cvc"]',
                'input[name*="security"]', 'input[name*="Security"]',
                'input[name*="ccCsc"]', 'input[name*="cc_csc"]',
                'input[id*="cvv"]', 'input[id*="cvc"]',
                'input[id*="CVV"]', 'input[id*="CVC"]',
                'input[id*="security"]', 'input[autocomplete="cc-csc"]',
                'input[autocomplete*="cc-csc"]',
                'input[placeholder*="CVV"]', 'input[placeholder*="cvv"]',
                'input[placeholder*="CVC"]', 'input[placeholder*="cvc"]',
                'input[placeholder*="Security"]', 'input[placeholder*="security"]'
            ], '\(cvv)');

            // CVV fallback: find a text input with maxlength 3 or 4 that's not filled yet
            if (!cvvFilled) {
                var cvvCandidates = Array.from(document.querySelectorAll('input[type="text"], input:not([type]), input[type="tel"], input[type="password"], input[type="number"]'))
                    .filter(function(el) {
                        return !filled.has(el) &&
                               (el.maxLength === 3 || el.maxLength === 4) &&
                               el.offsetWidth > 0;
                    });
                if (cvvCandidates.length > 0) {
                    fillElement(cvvCandidates[0], '\(cvv)', 'cvvFallback');
                }
            }

            // -- Email --
            fillField([
                'input[name*="email"]', 'input[name*="Email"]',
                'input[type="email"]', 'input[id*="email"]',
                'input[id*="Email"]', 'input[autocomplete="email"]',
                'input[autocomplete*="email"]',
                'input[placeholder*="email"]', 'input[placeholder*="Email"]'
            ], '\(email)');

            function fillElement(el, value, label) {
                el.focus();
                setNativeValue(el, value);
                filled.add(el);
                results.push(label + '=' + value);
            }

            return results.join(' | ');
        })();
        """
    }

