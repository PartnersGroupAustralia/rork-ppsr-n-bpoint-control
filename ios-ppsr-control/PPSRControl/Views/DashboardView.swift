import SwiftUI

/// Dashboard tab — status pill, start/stop, stat cards, doughnut + line charts.
/// Data updates live via the observable automation engine.
struct DashboardView: View {
    let settings: AppSettings
    let engine: PpsrAutomationEngine

    @State private var viewModel: DashboardViewModel?

    var body: some View {
        NavigationStack {
            ScrollView {
                VStack(spacing: 20) {
                    modeSection
                    statusPillSection
                    statCardsSection
                    chartsSection
                    progressSection
                }
                .padding(.horizontal)
                .padding(.bottom, 24)
            }
            .navigationTitle("Dashboard")
            .alert("Error", isPresented: .constant(viewModel?.errorMessage != nil)) {
                Button("OK") { viewModel?.clearError() }
            } message: {
                Text(viewModel?.errorMessage ?? "")
            }
        }
        .onAppear {
            if viewModel == nil {
                viewModel = DashboardViewModel(engine: engine)
            }
        }
    }

    private var vm: DashboardViewModel {
        viewModel ?? DashboardViewModel(engine: engine)
    }

    // MARK: - Mode Picker (main menu)

    /// The main menu: pick which flow Start runs — PPSR vehicle checks or Bpoint payments.
    private var modeSection: some View {
        VStack(spacing: 8) {
            Picker("Mode", selection: Binding(
                get: { settings.automationMode },
                set: { settings.automationMode = $0 }
            )) {
                ForEach(AutomationMode.allCases, id: \.self) { mode in
                    Label(mode.label, systemImage: mode.iconName)
                        .tag(mode)
                }
            }
            .pickerStyle(.segmented)

            if settings.automationMode == .bpoint {
                HStack(spacing: 6) {
                    Image(systemName: "dollarsign.circle")
                        .font(.caption)
                    Text("Payment amount: $\(settings.bpointAmount) — change in Settings")
                        .font(.caption)
                        .lineLimit(1)
                }
                .foregroundStyle(.secondary)
            }
        }
    }

    // MARK: - Status Pill + Toggle

    private var statusPillSection: some View {
        VStack(spacing: 16) {
            StatusPill(isRunning: vm.isRunning)

            if vm.autoGenerateData, let email = vm.currentRunEmail {
                HStack(spacing: 6) {
                    Image(systemName: "shuffle")
                        .font(.caption)
                    Text(email)
                        .font(.caption.monospacedDigit())
                        .lineLimit(1)
                }
                .foregroundStyle(.secondary)
                .padding(.horizontal, 12)
                .padding(.vertical, 6)
                .background(.thinMaterial, in: Capsule())
            }

            Button {
                if vm.isRunning {
                    vm.stop()
                } else {
                    vm.start(email: settings.email)
                }
            } label: {
                HStack(spacing: 10) {
                    Image(systemName: vm.isRunning ? "stop.fill" : "play.fill")
                    Text(vm.isRunning ? "Stop" : "Start")
                        .font(.headline)
                }
                .frame(maxWidth: .infinity)
                .padding(.vertical, 14)
            }
            .buttonStyle(.borderedProminent)
            .tint(vm.isRunning ? .red : .accentColor)
        }
        .padding(.top, 8)
    }

    // MARK: - Stat Cards

    private var statCardsSection: some View {
        LazyVGrid(
            columns: [GridItem(.flexible(), spacing: 12), GridItem(.flexible(), spacing: 12)],
            spacing: 12
        ) {
            StatCard(title: "Waiting", value: vm.queuedCardCount,
                     icon: "creditcard.stack", color: .cyan)
            StatCard(title: "Success", value: vm.stats.successCount,
                     icon: "checkmark.seal.fill", color: .green)
            StatCard(title: "Failed", value: vm.stats.failureCount,
                     icon: "xmark.octagon.fill", color: .red)
            StatCard(title: "Success Rate",
                     value: String(format: "%.1f%%", vm.stats.successRate),
                     icon: "chart.line.uptrend.xyaxis", color: .accentColor)
        }
    }

    // MARK: - Charts

    private var chartsSection: some View {
        VStack(spacing: 16) {
            if !vm.chartSegments.isEmpty {
                DoughnutChartCard(segments: vm.chartSegments)
            }
            if !vm.successRateTrend.isEmpty {
                LineChartCard(values: vm.successRateTrend)
            }
        }
    }

    // MARK: - Progress

    private var progressSection: some View {
        Group {
            if vm.progress.totalCards > 0 {
                ProgressCard(progress: vm.progress)
            }
        }
    }
}

// MARK: - Status Pill

private struct StatusPill: View {
    let isRunning: Bool

    var body: some View {
        HStack(spacing: 8) {
            Circle()
                .fill(isRunning ? .green : .secondary)
                .frame(width: 10, height: 10)
                .overlay {
                    if isRunning {
                        Circle()
                            .stroke(.green.opacity(0.4), lineWidth: 8)
                            .scaleEffect(1.3)
                            .opacity(0.5)
                    }
                }
                .animation(.easeInOut(duration: 0.8).repeatForever(), value: isRunning)

            Text(isRunning ? "Running" : "Stopped")
                .font(.subheadline.weight(.semibold))
        }
        .padding(.horizontal, 16)
        .padding(.vertical, 8)
        .background(.thinMaterial, in: Capsule())
    }
}

// MARK: - Stat Card

private struct StatCard: View {
    let title: String
    let value: Any
    let icon: String
    let color: Color

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                Image(systemName: icon)
                    .foregroundStyle(color)
                    .font(.title3)
                Spacer()
            }
            Text("\(value)")
                .font(.title.bold())
                .monospacedDigit()
                .foregroundStyle(color == .primary ? .primary : color)
            Text(title)
                .font(.caption)
                .foregroundStyle(.secondary)
        }
        .padding(14)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Color(.secondarySystemBackground),
                    in: .rect(cornerRadius: 14))
    }
}

// MARK: - Progress Card

private struct ProgressCard: View {
    let progress: PpsrProgress

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Label("Processing", systemImage: "gear")
                    .font(.subheadline.weight(.medium))
                Spacer()
                Text("\(progress.currentIndex) / \(progress.totalCards)")
                    .font(.subheadline.monospacedDigit())
                    .foregroundStyle(.secondary)
            }
            ProgressView(value: progress.fraction)
                .tint(.accentColor)
        }
        .padding(14)
        .background(Color(.secondarySystemBackground),
                    in: .rect(cornerRadius: 14))
    }
}

